
Definitions:
  Spatial release from masking (SRM): when spatial separation between a signal and masker decreases masking thresholds (SRT). Is there a benefit. SRM is the difference between SRT in two conditions. SRM here is the difference in SRT between diotic and dichotic listening. 


Participants = 16 adults with NH
DV = SRT (speech recognition threshold) of a target sentence
higher = worse 
SRM (spatial release from masking) or the SRT (dB) difference between diotic and dichotic conditions
a. Do you "achieve" SRM? That is, is there a benefit between diotic and dichotic?
  b. How different is the SRT in the diotic and dichotic conditions? 
  
  All stim presented with 16-channel vocoder.    
The target sentence was delivered to both ears. 
Two competing speech maskers. 

IVs:
  1. masker presentation 
a. diotic (both speech maskers delivered to both ears)
b. dichotic (one speech masker delivered L and the other R)
Diotic is harder than dichotic.
2. # channel interaction
a. limited channel interaction in both ears (L48R48)
b. limited channel interaction in 1 ear, broad interaction in other (L48R12)
c. broad channel interaction in both ears (L12R12)

Take-aways:
  - diotic is harder than dichotic
- SRT = broad interaction > broad/limited interaction > limited interaction 
- spectral smearing affects dichotic listening more than diotic
- SRM (benefit of dichotic over diotic) occurs in all channel interaction conditions
- SRM is larger with same channel (limited or broad) than combined (limited+broad)


